#!/usr/bin/env python3
"""Render ASCII 32..126 into a dense 8x8 bitmap font (host/sim fallback).

On real hardware the kernel uses the BIOS ROM font fetched in stage 2; the
host simulator has no BIOS, so it links this generated table instead. The
generated C file is committed — regenerating it only needs Pillow + a TTF.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126
GLYPHS = LAST - FIRST + 1
TTF_CANDIDATES = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
]


def find_font() -> str:
    for path in TTF_CANDIDATES:
        if os.path.exists(path):
            return path
    sys.exit("genfont: no suitable TTF found")


SS = 4                       # supersampling factor: 32x32 -> 8x8
CELL = 8 * SS                # 32 px high-res cell

# TTF outlines do not survive 8x8 for a few glyphs — hand-tuned bitmaps
# (bit 0x80 = leftmost pixel), in the spirit of classic VGA ROM fonts.
MANUAL = {
    ord("%"): [0x18, 0x24, 0x18, 0x30, 0x60, 0x90, 0x48, 0x30],
}


def render_glyph(font, ch: str) -> list[int]:
    # Render large and box-average 4x4 down: full-height crisp bitmap glyphs
    # without the halo pixels a plain bilinear resize would introduce.
    img = Image.new("L", (CELL, CELL), 0)
    draw = ImageDraw.Draw(img)
    draw.text((CELL // 2, CELL // 2), ch, font=font, fill=255, anchor="mm")
    hi = img.load()
    rows = []
    for y in range(8):
        byte = 0
        for x in range(8):
            total = 0
            for dy in range(SS):
                for dx in range(SS):
                    total += hi[x * SS + dx, y * SS + dy]
            if total // (SS * SS) > 90:
                byte |= 0x80 >> x
        rows.append(byte)
    return rows


def main(out_c: str) -> None:
    font = ImageFont.truetype(find_font(), 32)
    table = [MANUAL.get(c, render_glyph(font, chr(c)))
             for c in range(FIRST, LAST + 1)]
    with open(out_c, "w") as f:
        f.write("/* Generated by tools/genfont.py — do not edit. */\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"const uint8_t HOST_FONT_FIRST = {FIRST};\n")
        f.write(f"const uint8_t HOST_FONT_GLYPHS = {GLYPHS};\n")
        f.write("const uint8_t host_font8x8[%d][8] = {\n" % GLYPHS)
        for ch, rows in zip(range(FIRST, LAST + 1), table):
            label = chr(ch) if ch > 32 else " "
            f.write("    /* %3d '%s' */ " % (ch, label))
            f.write("{" + ",".join("0x%02X" % b for b in rows) + "},\n")
        f.write("};\n")
    print(f"genfont: {out_c} ({GLYPHS} glyphs)")


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) == 2 else "host/font8x8.c"
    main(out)
